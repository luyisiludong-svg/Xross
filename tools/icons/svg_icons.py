#!/usr/bin/env python3
"""
Converts the design SVGs in assets/icons into Android VectorDrawables.

The source files come in two shapes:
  * single icons: one <svg> with white <path>s (sometimes over a black backdrop <rect>)
  * sheets ("Group N.svg"): many icons, each in its own <g clip-path="url(#id)"> whose
    <clipPath> holds a translated <rect> marking the icon's bounds. Paths use sheet
    coordinates, so each icon's viewport is simply that rect.

Usage:
  svg_icons.py list  <assets/icons> <out_dir>          # split everything + preview.html
  svg_icons.py build <assets/icons> <icon_map.txt> <theme icons dir>

`build` writes one <name>.svg per mapped icon into the built-in Default theme pack
(app/src/main/assets/themes/default/icons), which ThemePackLoader reads at runtime with
theme/pack/SvgIcon.kt. Theme packs in Xross/themes/<id>/icons/ use the same names.

icon_map.txt lines:  <icon name> = <source id>   (ids as printed by `list`)
Only white fills are kept; black/none fills are backdrops and are dropped.
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

SVG_NS = "{http://www.w3.org/2000/svg}"
SKIP_FILES = {"icons_276.svg.svg"}  # master sheet with embedded rasters and gradients


def tag(el):
    return el.tag.replace(SVG_NS, "")


def is_white(fill):
    if fill is None:
        return True  # inherits; every source path that matters is white
    f = fill.strip().lower()
    return f in ("white", "#fff", "#ffffff")


def translate_of(el):
    m = re.search(r"translate\(\s*([-\d.eE]+)(?:[\s,]+([-\d.eE]+))?\s*\)", el.get("transform", ""))
    if not m:
        return 0.0, 0.0
    return float(m.group(1)), float(m.group(2) or 0.0)


def rect_to_path(r):
    x = float(r.get("x", 0)); y = float(r.get("y", 0))
    tx, ty = translate_of(r)
    x += tx; y += ty
    w = float(r.get("width")); h = float(r.get("height"))
    return f"M{x} {y}H{x + w}V{y + h}H{x}Z"


def collect_paths(el, clip_ids):
    """White path data under el, skipping <defs>/<clipPath> content."""
    out = []
    for child in el:
        t = tag(child)
        if t in ("defs", "clipPath"):
            continue
        if t == "path" and is_white(child.get("fill")) and child.get("d"):
            out.append((child.get("d"), child.get("fill-rule") == "evenodd"))
        elif t == "rect" and is_white(child.get("fill")) and child.get("fill") is not None:
            out.append((rect_to_path(child), False))
        elif t == "g":
            out.extend(collect_paths(child, clip_ids))
    return out


def clip_rects(root):
    rects = {}
    for cp in root.iter(SVG_NS + "clipPath"):
        r = cp.find(SVG_NS + "rect")
        if r is None:
            continue
        tx, ty = translate_of(r)
        rects[cp.get("id")] = (tx + float(r.get("x", 0)), ty + float(r.get("y", 0)),
                               float(r.get("width")), float(r.get("height")))
    return rects


def split_file(path):
    """Yields (id, (vx, vy, vw, vh), [(d, evenodd)])."""
    root = ET.parse(path).getroot()
    base = os.path.splitext(os.path.basename(path))[0]
    rects = clip_rects(root)
    groups = [g for g in root if tag(g) == "g"]
    sheet = len(groups) > 1 or os.path.basename(path).startswith("Group")
    if sheet:
        for i, g in enumerate(groups):
            m = re.search(r"url\(#([^)]+)\)", g.get("clip-path", ""))
            box = rects.get(m.group(1)) if m else None
            paths = collect_paths(g, rects)
            if box and paths:
                yield f"{base.replace(' ', '').lower()}_{i:02d}", box, paths
    else:
        vb = [float(v) for v in root.get("viewBox").split()]
        paths = collect_paths(root, rects)
        if paths:
            yield base.split("-")[0], tuple(vb), paths


def all_icons(src_dir):
    for name in sorted(os.listdir(src_dir)):
        if name.endswith(".svg") and name not in SKIP_FILES:
            yield from split_file(os.path.join(src_dir, name))


def vector_drawable(box, paths, size_dp=48):
    """VectorDrawable with the icon centred in a square viewport (keeps aspect ratio)."""
    x, y, w, h = box
    side = max(w, h)
    ox = x - (side - w) / 2
    oy = y - (side - h) / 2
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tools/icons/svg_icons.py from assets/icons. Do not edit. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{size_dp}dp" android:height="{size_dp}dp"',
        f'    android:viewportWidth="{side:.4f}" android:viewportHeight="{side:.4f}">',
        f'    <group android:translateX="{-ox:.4f}" android:translateY="{-oy:.4f}">',
    ]
    for d, evenodd in paths:
        ft = ' android:fillType="evenOdd"' if evenodd else ""
        lines.append(f'        <path android:fillColor="#FFFFFFFF"{ft} android:pathData="{d}" />')
    lines += ["    </group>", "</vector>", ""]
    return "\n".join(lines)


def pack_svg(box, paths):
    """Square, centred SVG for the theme pack: a viewBox and one translated group of white paths."""
    x, y, w, h = box
    side = max(w, h)
    ox = x - (side - w) / 2
    oy = y - (side - h) / 2
    lines = [
        "<!-- Generated by tools/icons/svg_icons.py from assets/icons. Do not edit. -->",
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {side:.4f} {side:.4f}">',
        f'  <g transform="translate({-ox:.4f} {-oy:.4f})">',
    ]
    for d, evenodd in paths:
        rule = ' fill-rule="evenodd"' if evenodd else ""
        lines.append(f'    <path fill="#FFFFFF"{rule} d="{d}"/>')
    lines += ["  </g>", "</svg>", ""]
    return "\n".join(lines)


def svg_preview(box, paths):
    x, y, w, h = box
    body = "".join(f'<path fill="white" fill-rule="{"evenodd" if e else "nonzero"}" d="{d}"/>' for d, e in paths)
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x} {y} {w} {h}">{body}</svg>'


def cmd_list(src, out):
    os.makedirs(out, exist_ok=True)
    cells = []
    for icon_id, box, paths in all_icons(src):
        with open(os.path.join(out, icon_id + ".svg"), "w") as f:
            f.write(svg_preview(box, paths))
        cells.append(
            f'<div class="c"><img src="{icon_id}.svg"><span>{icon_id}</span></div>')
        print(icon_id)
    with open(os.path.join(out, "preview.html"), "w") as f:
        f.write("<html><style>body{background:#3a3560;margin:6px;font:11px monospace;color:#ff0}"
                ".c{display:inline-block;width:118px;text-align:center;margin:4px}"
                "img{width:64px;height:64px;object-fit:contain;display:block;margin:auto}</style><body>"
                + "".join(cells) + "</body></html>")


def cmd_build(src, mapping, out_dir):
    icons = {icon_id: (box, paths) for icon_id, box, paths in all_icons(src)}
    os.makedirs(out_dir, exist_ok=True)
    for line in open(mapping):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        name, icon_id = [s.strip() for s in line.split("=", 1)]
        if icon_id not in icons:
            sys.exit(f"unknown icon id {icon_id!r} for {name}")
        box, paths = icons[icon_id]
        with open(os.path.join(out_dir, f"{name}.svg"), "w") as f:
            f.write(pack_svg(box, paths))
        print(f"{name}.svg  <-  {icon_id}")


if __name__ == "__main__":
    if len(sys.argv) >= 4 and sys.argv[1] == "list":
        cmd_list(sys.argv[2], sys.argv[3])
    elif len(sys.argv) >= 5 and sys.argv[1] == "build":
        cmd_build(sys.argv[2], sys.argv[3], sys.argv[4])
    else:
        sys.exit(__doc__)
